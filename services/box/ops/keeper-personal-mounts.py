#!/usr/bin/env python3
"""Render the keeper's mounts for the personal Google and Microsoft files its settings name.

keeper.json (lifecycle.runtime.google and lifecycle.runtime.microsoft) names secret files the keeper
reads from inside its container. compose.lares-keeper.yaml mounts only fixed files, so each named file
needs its own read-only bind, at the same path. This writes that compose override, and refuses, before
anything is changed, when a named file is missing, linked, shared, not owned by root, or outside the
secrets folder. Nothing is written when keeper.json names no such file.

usage: keeper-personal-mounts.py <keeper.json> <output> <secrets-dir> <prefix>
"""
import json
import os
import stat
import sys

MICROSOFT_FIELDS = ("tenantIdFile", "clientIdFile", "clientSecretFile", "tokenKeyFile")


def named_files(config: dict) -> list[str]:
    runtime = config.get("lifecycle", {}).get("runtime", {})
    files: list[str] = []
    google = runtime.get("google")
    if isinstance(google, dict):
        files.append(google.get("tokenKeyFile"))
        for client in (google.get("clients") or {}).values():
            files += [client.get("clientIdFile"), client.get("clientSecretFile")]
    microsoft = runtime.get("microsoft")
    if isinstance(microsoft, dict):
        files += [microsoft.get(field) for field in MICROSOFT_FIELDS]
    if not all(isinstance(path, str) and path for path in files):
        raise ValueError("keeper.json names a personal Google or Microsoft file without a path")
    return sorted(set(files))


def check(path: str, secrets_dir: str, owner_uid: int) -> None:
    folder = os.path.normpath(secrets_dir)
    if os.path.normpath(path) != path or not os.path.isabs(path) or not path.startswith(folder + "/"):
        raise ValueError(f"{path} is not a plain path inside {folder}. Keep the file there")
    try:
        info = os.lstat(path)
    except OSError:
        raise ValueError(f"{path} does not exist on this server. Create it (the Google setup helper writes it) and run this again") from None
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size == 0:
        raise ValueError(f"{path} must be a single, non-empty, plain file (not a link, copy-link or folder)")
    if info.st_uid != owner_uid:
        raise ValueError(f"{path} must be owned by root")


def render(files: list[str]) -> str:
    lines = ["# Generated by install.sh from keeper.json. Do not edit.",
             "# Exact read-only binds for the personal Google and Microsoft files keeper.json names.",
             "services:", "  lares-keeper:", "    volumes:"]
    for path in files:
        quoted = json.dumps(path)
        lines += ["      - type: bind", f"        source: {quoted}", f"        target: {quoted}",
                  "        read_only: true", "        bind:", "          create_host_path: false"]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 5:
        print(__doc__, file=sys.stderr)
        return 64
    config_path, output, secrets_dir, prefix = argv[1:]
    # With a real installation the files belong to root. A disposable test prefix belongs to whoever made it.
    owner_uid = 0 if prefix in ("", "/") else os.geteuid()
    try:
        with open(config_path, encoding="utf-8") as stream:
            files = named_files(json.load(stream))
        for path in files:
            check(path, secrets_dir, owner_uid)
    except (OSError, ValueError, AttributeError) as error:
        print(f"keeper-personal-mounts: {error}", file=sys.stderr)
        return 1
    if files:
        with open(output, "w", encoding="utf-8") as stream:
            stream.write(render(files))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
