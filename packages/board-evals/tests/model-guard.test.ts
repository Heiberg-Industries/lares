// Every agent this package builds must be unable to reach a model provider.
//
// A scripted `mockModel` is not enough: eve keeps only a model's id between steps and, picking a
// conversation up cold, resolves that id again through the AI SDK's default provider, which
// reaches a hosted gateway. The kit's `installRefusingDefaultProvider()` replaces that default
// with one that refuses, and locks it. These tests pin that the guard is in the committed fixture
// agent (as the first statement, and effective once the file is loaded) and in every agent source
// a script in this package generates.
import { readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, it, expect } from "vitest";

const at = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));
const GUARD_IMPORT = /import\s*\{\s*installRefusingDefaultProvider\s*\}\s*from\s*["']@lares\/agent-kit\/gateway-budget["'];?/;

/** The first statement of a module source that is neither an import nor a comment. */
function firstStatement(source: string): string {
  const withoutComments = source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
  const withoutImports = withoutComments.replace(/^\s*import\s[^;]*;?\s*$/gm, "");
  return withoutImports.trim().split("\n")[0]!.trim();
}

describe("the fixture agent's model guard", () => {
  it("is an instrumentation file where eve 1.0 reads one, and the removed single file is absent", () => {
    expect(readdirSync(at("agent/instrumentation"))).toContain("model-guard.ts");
    expect(readdirSync(at("agent"))).not.toContain("instrumentation.ts");
  });

  it("installs the guard as its first statement", () => {
    const source = readFileSync(at("agent/instrumentation/model-guard.ts"), "utf8");
    expect(source).toMatch(GUARD_IMPORT);
    expect(firstStatement(source)).toBe("installRefusingDefaultProvider();");
  });

  it("leaves the AI SDK's default provider refusing every request once loaded, and locked", async () => {
    await import("../agent/instrumentation/model-guard.js");
    const descriptor = Object.getOwnPropertyDescriptor(globalThis, "AI_SDK_DEFAULT_PROVIDER");
    expect(descriptor).toBeDefined();
    expect(descriptor!.writable).toBe(false);
    expect(descriptor!.configurable).toBe(false);
    const provider = descriptor!.value as { languageModel(id: string): { doGenerate(): unknown; doStream(): unknown } };
    expect(() => provider.languageModel("anthropic/some-model").doGenerate()).toThrow("outside the engine's gateway");
    expect(() => provider.languageModel("anthropic/some-model").doStream()).toThrow("outside the engine's gateway");
    expect(() => { (globalThis as Record<string, unknown>)["AI_SDK_DEFAULT_PROVIDER"] = {}; }).toThrow();
  });
});

describe("agent sources generated by this package's scripts", () => {
  // Each of these scripts writes an instrumentation file into a disposable agent. The source is a
  // template literal (the web-chat proofs) or an array of lines (the measurement), read here as
  // text: the scripts need Docker to run, this check does not.
  const templateOf = (script: string): string => {
    const text = readFileSync(at(`scripts/${script}`), "utf8");
    const match = /const INSTRUMENTATION_SRC = `([\s\S]*?)`;/.exec(text);
    expect(match, `${script} no longer declares INSTRUMENTATION_SRC`).not.toBeNull();
    return match![1]!;
  };

  it.each(["web-chat-proof.mjs", "web-chat-approval-proof.mjs"])("%s: the generated instrumentation installs the guard first", (script) => {
    const source = templateOf(script);
    expect(source).toMatch(GUARD_IMPORT);
    expect(firstStatement(source)).toBe("installRefusingDefaultProvider();");
    // And it is written where eve 1.0 reads it, not to the removed single file.
    const text = readFileSync(at(`scripts/${script}`), "utf8");
    expect(text).toMatch(/agent\/instrumentation\/[a-z-]+\.ts'\), INSTRUMENTATION_SRC\)/);
    expect(text).not.toContain("'agent/instrumentation.ts'");
  });

  it("session-rows-measure.mjs: the inline agent gets an instrumentation file that installs the guard first", () => {
    const text = readFileSync(at("scripts/session-rows-measure.mjs"), "utf8");
    const block = /join\(root, 'agent\/instrumentation\/model-guard\.ts'\),\s*\[([\s\S]*?)\]\.join/.exec(text);
    expect(block, "the measurement no longer writes agent/instrumentation/model-guard.ts").not.toBeNull();
    const lines = [...block![1]!.matchAll(/^\s*(["'])(.*)\1,\s*$/gm)].map((m) => m[2]!);
    const source = lines.join("\n");
    expect(source).toMatch(GUARD_IMPORT);
    expect(firstStatement(source)).toBe("installRefusingDefaultProvider();");
  });

  it("no script in this package writes an agent without the fixture's guard or one of its own", () => {
    // A script that builds an agent either copies this fixture (proof-harness `makeApp`, which
    // carries agent/instrumentation/model-guard.ts with it) or builds a role service (which has
    // its own). The one script that writes an agent from nothing is the measurement, checked
    // above. This pins the list, so a new script that writes its own `agent/agent.ts` fails here
    // until it is added and guarded.
    const writers = readdirSync(at("scripts"))
      .filter((name) => /\.(mjs|sh)$/.test(name))
      .filter((name) => /join\(root, 'agent\/agent\.ts'\),\s*\[/.test(readFileSync(at(`scripts/${name}`), "utf8")));
    expect(writers).toEqual(["session-rows-measure.mjs"]);
  });
});
